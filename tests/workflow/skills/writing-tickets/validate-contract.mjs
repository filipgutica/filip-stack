import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { workflowSkillRoot } from '../../plugin-paths.mjs'

const skillRoot = workflowSkillRoot('writing-tickets')
const writingTickets = await readFile(new URL('SKILL.md', skillRoot), 'utf8')
const specToTickets = await readFile(new URL('../spec-to-tickets/SKILL.md', skillRoot), 'utf8')
const storage = await readFile(new URL('../setup/references/storage.md', skillRoot), 'utf8')
const setup = await readFile(new URL('../setup/SKILL.md', skillRoot), 'utf8')
const planningFlow = await readFile(new URL('../coordinator/references/planning-flow.md', skillRoot), 'utf8')
const storageLocalTickets = storage.split('\n## ').find((section) => section.startsWith('Local tickets\n'))
const writingLocalLinks = writingTickets.split('\n## ')
  .find((section) => section.startsWith('Local ticket links\n'))

assert.ok(storageLocalTickets, 'Storage must define the Local tickets section')
assert.ok(writingLocalLinks, 'Writing Tickets must define the Local ticket links section')

assert.match(writingTickets, /^## Ticket hierarchy and relationships$/m)
assert.match(writingTickets, /external parent.+specification or ERD/i)
assert.match(writingTickets, /After verification, prepare a metadata link with the system, ID, and URL/i)
assert.match(writingTickets, /Require explicit external-artifact authority for the local source before changing its `Ticket` metadata/i)
assert.match(writingTickets, /Without that authority, return the proposed link in the conversation/i)
assert.match(writingTickets, /Do not require the external parent to link back to the local file/i)
assert.doesNotMatch(writingTickets, /Link the epic to the source document/i)
assert.match(writingTickets, /Reuse a verified epic or parent issue/i)
assert.match(writingTickets, /Draft one if none exists/i)
assert.match(writingTickets, /Story or issue.+verified external parent/i)
assert.match(writingTickets, /^### External parent$/m)
assert.match(writingTickets, /`## Children`/)
assert.doesNotMatch(writingTickets, /^### Epic$/m)
assert.match(writingTickets, /subtask.+complex story/i)
assert.match(writingTickets, /verified.+ticket.+link/i)
assert.match(writingTickets, /blocks/i)
assert.match(writingTickets, /is blocked by/i)
assert.match(writingTickets, /preced/i)
assert.match(writingTickets, /follow/i)
assert.match(writingTickets, /supersed/i)
assert.match(writingTickets, /superseded by/i)
assert.match(writingTickets, /publishing authority/i)

assert.match(specToTickets, /one external parent issue.+specification or ERD/i)
assert.match(specToTickets, /local Markdown tickets, Jira tickets, or GitHub issues/i)
assert.match(specToTickets, /Search for an existing epic or parent issue/i)
assert.match(specToTickets, /story or issue.+child.+verified external parent/i)
assert.match(specToTickets, /Require explicit external-artifact authority for the local source before changing its `Ticket` metadata/i)
assert.match(specToTickets, /subtask/i)
assert.match(specToTickets, /topics\/open\/<topic-id>\/tickets\/todo\//)
assert.match(specToTickets, /containing lifecycle directory.+authoritative status/i)
assert.match(specToTickets, /TICKET-001-short-title\.md/)
assert.match(specToTickets, /externalLinks/)
assert.match(writingLocalLinks, /externalLinks/)
assert.match(writingLocalLinks, /Do not add the external ID to the filename/)
assert.match(storageLocalTickets, /^externalLinks:$/m)
assert.match(storageLocalTickets, /optional YAML sequence of mappings/i)
assert.match(storageLocalTickets, /only `system`, `id`, and `url`/)
assert.match(storageLocalTickets, /all three values must be strings/i)
assert.match(storageLocalTickets, /same external system/i)
assert.match(storageLocalTickets, /Do not add Jira, GitHub, or other external IDs to the filename/)
assert.match(storageLocalTickets, /Do not add external status/i)
assert.match(storageLocalTickets, /does not grant publishing authority/i)
assert.match(storage, /externalTicketSystem/)
assert.match(storage, /does not grant publishing authority/i)
assert.match(storage, /`ticketBackend` can be `local`, `jira`, or `github`/)
assert.match(storage, /`externalTicketSystem\.system` must match `ticketBackend`/)
assert.match(specToTickets, /For the `github` backend/)
assert.match(setup, /ask the user to choose `local`, `jira`, or `github`/)
assert.match(setup, /Do not infer the backend from the Git remote/)
assert.match(setup, /reuses identical configuration and stops on conflicts/i)
assert.match(storage, /local` backend stores canonical Markdown tickets/i)
assert.match(storage, /jira` and `github` backends use external issues as canonical tickets/i)
assert.match(storage, /do not create mirrored local ticket files/i)
assert.match(specToTickets, /Do not persist a mirrored local Markdown ticket/i)
assert.match(writingLocalLinks, /external issue is canonical/i)
assert.match(writingLocalLinks, /Do not create a mirrored local ticket file or local status/i)
assert.match(storage, /standalone Jira or GitHub issue does not require a topic/i)
assert.match(storage, /Each local artifact links to its `TOPIC\.md`/i)
assert.match(specToTickets, /Jira or GitHub issue does not require a topic/i)
assert.match(specToTickets, /valid repository workflow configuration/i)
assert.match(specToTickets, /explicit publishing authority for writes/i)
assert.match(planningFlow, /For a persisted local artifact, use `topics` to resolve its open topic/i)
assert.match(setup, /Topics are required for persisted local artifacts/i)
assert.match(setup, /Standalone Jira or GitHub issues do not require a topic/i)

console.log('Writing Tickets hierarchy contract passed.')
